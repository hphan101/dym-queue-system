export async function deactivateClinicRoomFromDate(
  roomId: string,
  effectiveDate: string,
): Promise<ClinicRoom> {
  const updated = await updateClinicRoom(roomId, {
    inactive_from: effectiveDate,
  });

  // Clean up any assignments in this room on or after effectiveDate so no hidden costs remain
  const { data: futureSchedules } = await supabase
    .from('roster_schedules')
    .select('id')
    .eq('schedule_type', 'insite')
    .eq('branch_code', updated.branch_code)
    .gte('schedule_date', effectiveDate);

  const scheduleIds = (futureSchedules ?? []).map((s) => s.id as string);
  if (scheduleIds.length > 0) {
    await supabase
      .from('roster_assignments')
      .delete()
      .in('schedule_id', scheduleIds)
      .eq('room_id', roomId);
  }

  return updated;
}

