export function formatCurrencyInput(amount: number): string {
  const safeAmount = Number.isFinite(amount) ? Math.round(amount) : 0;
  if (safeAmount <= 0) return '';
  return new Intl.NumberFormat('vi-VN').format(safeAmount);
}

export function parseCurrencyInput(raw: string): number {
  const digitsOnly = raw.replace(/\D/g, '');
  if (!digitsOnly) return 0;
  return Number.parseInt(digitsOnly, 10) || 0;
}

export function getMonthRange(monthStr: string): { startDate: string; endDate: string } {
  const [yearPart, monthPart] = monthStr.split('-').map(Number);
  const year = yearPart || new Date().getFullYear();
  const month = monthPart || new Date().getMonth() + 1;
  const lastDay = new Date(year, month, 0).getDate();
  const mm = String(month).padStart(2, '0');
  const dd = String(lastDay).padStart(2, '0');
  return {
    startDate: `${year}-${mm}-01`,
    endDate: `${year}-${mm}-${dd}`,
  };
}

// 1. Medical Personnel CRUD
export async function fetchMedicalPersonnel(): Promise<MedicalPersonnel[]> {
  const [personnelRes, assignRefsRes] = await Promise.all([
    supabase
      .from('medical_personnel')
      .select('*')
      .order('is_active', { ascending: false })
      .order('role_type', { ascending: true })
      .order('personnel_code', { ascending: true }),
    supabase.from('roster_assignments').select('personnel_id'),
  ]);

  if (personnelRes.error) {
    throw new Error(
      personnelRes.error.message || 'Không thể tải danh mục nhân sự.',
    );
  }

  const countByPersonId = new Map<string, number>();
  for (const row of (assignRefsRes.data ?? []) as Array<{
    personnel_id: string;
  }>) {
    if (!row.personnel_id) continue;
    countByPersonId.set(
      row.personnel_id,
      (countByPersonId.get(row.personnel_id) ?? 0) + 1,
    );
  }

  return ((personnelRes.data ?? []) as MedicalPersonnel[]).map((row) => ({
    ...row,
    fixed_cost: Number(row.fixed_cost ?? 0),
    assignment_count: countByPersonId.get(row.id) ?? 0,
  }));
}

export async function saveMedicalPersonnel(
  input: MedicalPersonnelInput,
): Promise<MedicalPersonnel> {
  const payload = {
    personnel_code: input.personnel_code.trim().toUpperCase(),
    full_name: input.full_name.trim(),
    role_type: input.role_type,
    phone_number: input.phone_number.trim(),
    email: input.email.trim(),
    fixed_cost: Math.max(0, Math.round(Number(input.fixed_cost) || 0)),
    is_active: input.is_active ?? true,
    updated_at: new Date().toISOString(),
  };

  if (input.id) {
    const { data, error } = await supabase
      .from('medical_personnel')
      .update(payload)
      .eq('id', input.id)
      .select('*')
      .single();

    if (error) {
      if (error.code === '23505') {
        throw new Error(`Mã nhân sự "${payload.personnel_code}" đã tồn tại.`);
      }
      throw new Error(error.message || 'Không thể cập nhật nhân sự.');
    }
    return {
      ...(data as MedicalPersonnel),
      fixed_cost: Number(data.fixed_cost ?? 0),
    };
  }

  const { data, error } = await supabase
    .from('medical_personnel')
    .insert(payload)
    .select('*')
    .single();

  if (error) {
    if (error.code === '23505') {
      throw new Error(`Mã nhân sự "${payload.personnel_code}" đã tồn tại.`);
    }
    throw new Error(error.message || 'Không thể thêm nhân sự mới.');
  }

  return {
    ...(data as MedicalPersonnel),
    fixed_cost: Number(data.fixed_cost ?? 0),
    assignment_count: 0,
  };
}

