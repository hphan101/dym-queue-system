export async function duplicateOnsiteCampaign(
  input: OnsiteScheduleInput,
  sourceAssignments: RosterAssignment[],
  copyAssignments: boolean,
): Promise<{
  schedule: RosterSchedule;
  insertedAssignments: RosterAssignment[];
}> {
  const createdSchedule = await saveOnsiteSchedule({
    ...input,
    id: null,
  });

  if (!copyAssignments || sourceAssignments.length === 0) {
    return { schedule: createdSchedule, insertedAssignments: [] };
  }

  const targetAllowance = Math.max(
    0,
    Math.round(Number(input.default_allowance ?? createdSchedule.default_allowance) || 0),
  );

  const payloads = sourceAssignments.map((item, idx) => ({
    schedule_id: createdSchedule.id,
    room_id: null,
    daily_override_id: null,
    position_label: item.position_label,
    personnel_id: item.personnel_id,
    shift_period: item.shift_period,
    base_cost_snapshot: Math.max(0, Math.round(Number(item.base_cost_snapshot) || 0)),
    allowance_cost:
      input.default_allowance !== undefined
        ? targetAllowance
        : Math.max(0, Math.round(Number(item.allowance_cost) || 0)),
    note: item.note || '',
    sort_order: item.sort_order ?? (idx + 1) * 10,
  }));

  const { data: insertedData, error: insertErr } = await supabase
    .from('roster_assignments')
    .insert(payloads)
    .select('*');

  if (insertErr) {
    throw new Error(
      insertErr.message || 'Đã tạo đoàn mới nhưng không thể sao chép nhân sự.',
    );
  }

  const insertedAssignments = ((insertedData ?? []) as RosterAssignment[]).map(
    (a) => ({
      ...a,
      daily_override_id: a.daily_override_id ?? null,
      base_cost_snapshot: Number(a.base_cost_snapshot ?? 0),
      allowance_cost: Number(a.allowance_cost ?? 0),
      total_cost: Number(
        a.total_cost ??
          Number(a.base_cost_snapshot ?? 0) + Number(a.allowance_cost ?? 0),
      ),
    }),
  );

  return { schedule: createdSchedule, insertedAssignments };
}

