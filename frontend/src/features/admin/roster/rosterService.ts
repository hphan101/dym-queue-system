export async function hideCatalogRoomForDate(
  branchCode: BranchCode,
  scheduleDate: string,
  roomId: string,
  scheduleId?: string | null,
): Promise<DailyRoomOverride> {
  if (scheduleId) {
    const { error: delAssignErr } = await supabase
      .from('roster_assignments')
      .delete()
      .eq('schedule_id', scheduleId)
      .eq('room_id', roomId);

    if (delAssignErr) {
      throw new Error(
        delAssignErr.message || 'Không thể xóa ca trực của phòng đang ẩn.',
      );
    }
  }

  const { data, error } = await supabase
    .from('roster_daily_room_overrides')
    .insert({
      schedule_date: scheduleDate,
      branch_code: branchCode,
      override_type: 'hide',
      room_id: roomId,
      custom_room_name: '',
      display_order: 999,
    })
    .select('*')
    .single();

  if (error) {
    if (error.code === '23505') {
      const { data: existing } = await supabase
        .from('roster_daily_room_overrides')
        .select('*')
        .eq('schedule_date', scheduleDate)
        .eq('branch_code', branchCode)
        .eq('override_type', 'hide')
        .eq('room_id', roomId)
        .single();
      if (existing) return existing as DailyRoomOverride;
    }
    throw new Error(error.message || 'Không thể ẩn phòng trong ngày.');
  }

  return data as DailyRoomOverride;
}

