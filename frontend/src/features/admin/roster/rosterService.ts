export async function bulkImportMedicalPersonnel(
  items: MedicalPersonnelInput[],
): Promise<MedicalPersonnel[]> {
  if (items.length === 0) return [];

  const nowIso = new Date().toISOString();
  const payloads = items.map((item) => ({
    personnel_code: item.personnel_code.trim().toUpperCase(),
    full_name: item.full_name.trim(),
    role_type: item.role_type,
    phone_number: item.phone_number.trim(),
    email: item.email.trim(),
    fixed_cost: Math.max(0, Math.round(Number(item.fixed_cost) || 0)),
    is_active: item.is_active ?? true,
    updated_at: nowIso,
  }));

  const { data, error } = await supabase
    .from('medical_personnel')
    .upsert(payloads, { onConflict: 'personnel_code' })
    .select('*');

  if (error) {
    throw new Error(error.message || 'Không thể nhập danh sách nhân sự.');
  }

  return ((data ?? []) as MedicalPersonnel[]).map((row) => ({
    ...row,
    fixed_cost: Number(row.fixed_cost ?? 0),
    assignment_count: 0,
  }));
}

export async function deleteOrArchiveMedicalPersonnel(
  id: string,
): Promise<{ action: 'deleted' | 'archived' }> {
  const { error } = await supabase
    .from('medical_personnel')
    .delete()
    .eq('id', id);

  if (!error) {
    return { action: 'deleted' };
  }

  // If referenced by existing assignments (foreign key restrict), archive instead
  if (error.code === '23503') {
    const { error: updateErr } = await supabase
      .from('medical_personnel')
      .update({ is_active: false, updated_at: new Date().toISOString() })
      .eq('id', id);

    if (updateErr) {
      throw new Error(updateErr.message || 'Không thể ngừng kích hoạt nhân sự.');
    }
    return { action: 'archived' };
  }

  throw new Error(error.message || 'Không thể xóa nhân sự.');
}

