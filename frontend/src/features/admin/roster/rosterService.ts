export function doShiftsOverlap(
  shiftA: ShiftPeriod,
  shiftB: ShiftPeriod,
): boolean {
  if (shiftA === 'FULL' || shiftB === 'FULL') return true;
  return shiftA === shiftB;
}

export function formatMonthTag(monthStr: string): string {
  const [year, month] = monthStr.split('-');
  if (!year || !month) return monthStr;
  return `T${Number(month)}-${year}`;
}

export function summarizeAssignmentCosts(
  list: Array<Pick<RosterAssignment, 'base_cost_snapshot' | 'allowance_cost'>>,
): {
  baseCost: number;
  allowanceCost: number;
  totalCost: number;
} {
  let baseCost = 0;
  let allowanceCost = 0;
  for (const item of list) {
    baseCost += Number(item.base_cost_snapshot ?? 0);
    allowanceCost += Number(item.allowance_cost ?? 0);
  }
  return {
    baseCost,
    allowanceCost,
    totalCost: baseCost + allowanceCost,
  };
}

export function shiftIsoDate(isoDate: string, deltaDays: number): string {
  const [y, m, d] = isoDate.split('-').map(Number);
  if (!y || !m || !d) return isoDate;
  const dateObj = new Date(Date.UTC(y, m - 1, d + deltaDays));
  const year = dateObj.getUTCFullYear();
  const month = String(dateObj.getUTCMonth() + 1).padStart(2, '0');
  const day = String(dateObj.getUTCDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

