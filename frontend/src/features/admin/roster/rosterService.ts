export function isAutoGeneratedPersonnelCode(code: string): boolean {
  const trimmed = code.trim();
  if (!trimmed) return true;
  return /^(BS|DD|NS|KTV|CTV)-\d+$/i.test(trimmed);
}

export function generateNextPersonnelCode(
  roleType: PersonnelRoleType,
  existingList: Array<Pick<MedicalPersonnel, 'personnel_code' | 'role_type'>>,
): string {
  const prefix = ROLE_CODE_PREFIXES[roleType];
  const existingCodesUpper = new Set(
    existingList.map((p) => p.personnel_code.trim().toUpperCase()),
  );

  // Match codes for this role or prefix (including legacy NS- for nurse)
  const prefixPattern =
    roleType === 'nurse'
      ? /^(?:DD|NS)-(\d+)$/i
      : new RegExp(`^${prefix}-(\\d+)$`, 'i');

  let maxNum = 0;
  for (const item of existingList) {
    const match = item.personnel_code.trim().match(prefixPattern);
    if (match) {
      const num = Number.parseInt(match[1], 10);
      if (Number.isFinite(num) && num > maxNum) {
        maxNum = num;
      }
    }
  }

  let candidateNum = maxNum + 1;
  let candidateCode = `${prefix}-${String(candidateNum).padStart(3, '0')}`;
  while (existingCodesUpper.has(candidateCode.toUpperCase())) {
    candidateNum += 1;
    candidateCode = `${prefix}-${String(candidateNum).padStart(3, '0')}`;
  }

  return candidateCode;
}

