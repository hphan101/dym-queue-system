export interface CopyInsiteScheduleResult {
  copiedCount: number;
  copiedRoomsCount: number;
  skippedCount: number;
  sourceTotalCount: number;
  targetSchedule: RosterSchedule | null;
  insertedAssignments: RosterAssignment[];
  insertedOverrides: DailyRoomOverride[];
}

export async function copyInsiteScheduleFromDate(
  branchCode: BranchCode,
  sourceDate: string,
  targetDate: string,
): Promise<CopyInsiteScheduleResult> {
  // 1. Fetch source schedule, source 'add' overrides, target overrides, and branch catalog rooms
  const [
    { data: sourceSchedule, error: sourceScheduleErr },
    { data: sourceAddOverridesData, error: sourceOverridesErr },
    { data: targetOverridesData, error: targetOverridesErr },
    { data: branchRoomsData, error: branchRoomsErr },
  ] = await Promise.all([
    supabase
      .from('roster_schedules')
      .select('*')
      .eq('schedule_type', 'insite')
      .eq('branch_code', branchCode)
      .eq('schedule_date', sourceDate)
      .maybeSingle(),
    supabase
      .from('roster_daily_room_overrides')
      .select('*')
      .eq('branch_code', branchCode)
      .eq('schedule_date', sourceDate)
      .eq('override_type', 'add')
      .order('display_order', { ascending: true }),
    supabase
      .from('roster_daily_room_overrides')
      .select('*')
      .eq('branch_code', branchCode)
      .eq('schedule_date', targetDate),
    supabase
      .from('clinic_rooms')
      .select('*')
      .eq('branch_code', branchCode),
  ]);

  if (sourceScheduleErr) {
    throw new Error(
      sourceScheduleErr.message || 'Không thể đọc lịch ngày hôm qua.',
    );
  }
  if (sourceOverridesErr || targetOverridesErr || branchRoomsErr) {
    throw new Error('Không thể đọc danh sách phòng khi sao chép lịch.');
  }

  const sourceAddOverrides = (sourceAddOverridesData ??
    []) as DailyRoomOverride[];
  const targetOverrides = (targetOverridesData ?? []) as DailyRoomOverride[];
  const branchRooms = (branchRoomsData ?? []) as ClinicRoom[];

  // Active fixed catalog room IDs on targetDate (excluding hidden rooms on targetDate)
  const hiddenRoomIdsOnTarget = new Set(
    targetOverrides
      .filter((o) => o.override_type === 'hide' && o.room_id)
      .map((o) => o.room_id as string),
  );
  const validFixedRoomIdsOnTarget = new Set(
    branchRooms
      .filter(
        (r) =>
          r.is_active &&
          (!r.inactive_from || targetDate < r.inactive_from) &&
          !hiddenRoomIdsOnTarget.has(r.id),
      )
      .map((r) => r.id),
  );

  // Copy temporary 'add' ("Chỉ hôm nay") rooms from sourceDate to targetDate
  const existingTargetAddByLowerName = new Map<string, DailyRoomOverride>();
  for (const ov of targetOverrides) {
    if (ov.override_type === 'add') {
      existingTargetAddByLowerName.set(
        ov.custom_room_name.trim().toLowerCase(),
        ov,
      );
    }
  }

  const overrideIdMap = new Map<string, string>();
  const insertedOverrides: DailyRoomOverride[] = [];

  for (const srcOv of sourceAddOverrides) {
    const key = srcOv.custom_room_name.trim().toLowerCase();
    const existingTargetOv = existingTargetAddByLowerName.get(key);
    if (existingTargetOv) {
      overrideIdMap.set(srcOv.id, existingTargetOv.id);
    } else {
      const { data: createdOv, error: createOvErr } = await supabase
        .from('roster_daily_room_overrides')
        .insert({
          schedule_date: targetDate,
          branch_code: branchCode,
          override_type: 'add',
          room_id: null,
          custom_room_name: srcOv.custom_room_name.trim(),
          display_order: srcOv.display_order,
        })
        .select('*')
        .single();

      if (!createOvErr && createdOv) {
        const typedOv = createdOv as DailyRoomOverride;
        insertedOverrides.push(typedOv);
        existingTargetAddByLowerName.set(key, typedOv);
        overrideIdMap.set(srcOv.id, typedOv.id);
      }
    }
  }

  if (!sourceSchedule) {
    return {
      copiedCount: 0,
      copiedRoomsCount: insertedOverrides.length,
      skippedCount: 0,
      sourceTotalCount: 0,
      targetSchedule: null,
      insertedAssignments: [],
      insertedOverrides,
    };
  }

  const { data: sourceAssignmentsData, error: sourceAssignErr } = await supabase
    .from('roster_assignments')
    .select('*')
    .eq('schedule_id', (sourceSchedule as RosterSchedule).id)
    .order('sort_order', { ascending: true })
    .order('created_at', { ascending: true });

  if (sourceAssignErr) {
    throw new Error(
      sourceAssignErr.message || 'Không thể đọc danh sách phân công hôm qua.',
    );
  }

  const sourceAssignments = (sourceAssignmentsData ?? []) as RosterAssignment[];
  if (sourceAssignments.length === 0) {
    return {
      copiedCount: 0,
      copiedRoomsCount: insertedOverrides.length,
      skippedCount: 0,
      sourceTotalCount: 0,
      targetSchedule: null,
      insertedAssignments: [],
      insertedOverrides,
    };
  }

  const targetSchedule = await ensureInsiteSchedule(branchCode, targetDate);

  const { data: existingTargetData, error: existingTargetErr } = await supabase
    .from('roster_assignments')
    .select('room_id, daily_override_id, personnel_id, shift_period')
    .eq('schedule_id', targetSchedule.id);

  if (existingTargetErr) {
    throw new Error(
      existingTargetErr.message ||
        'Không thể kiểm tra phân công hiện tại của ngày đích.',
    );
  }

  const existingKeys = new Set(
    (existingTargetData ?? []).map(
      (item) =>
        `${item.room_id ?? ''}|${item.daily_override_id ?? ''}|${item.personnel_id}|${item.shift_period}`,
    ),
  );

  const payloadsToInsert: Array<Record<string, unknown>> = [];

  for (const item of sourceAssignments) {
    let targetRoomId: string | null = null;
    let targetDailyOverrideId: string | null = null;

    if (item.room_id) {
      // Skip if fixed room is deactivated or hidden on targetDate
      if (!validFixedRoomIdsOnTarget.has(item.room_id)) {
        continue;
      }
      targetRoomId = item.room_id;
    } else if (item.daily_override_id) {
      targetDailyOverrideId =
        overrideIdMap.get(item.daily_override_id) ?? null;
      if (!targetDailyOverrideId) {
        continue;
      }
    } else {
      continue;
    }

    const key = `${targetRoomId ?? ''}|${targetDailyOverrideId ?? ''}|${item.personnel_id}|${item.shift_period}`;
    if (existingKeys.has(key)) {
      continue;
    }
    existingKeys.add(key);

    payloadsToInsert.push({
      schedule_id: targetSchedule.id,
      room_id: targetRoomId,
      daily_override_id: targetDailyOverrideId,
      position_label: item.position_label,
      personnel_id: item.personnel_id,
      shift_period: item.shift_period,
      base_cost_snapshot: Math.max(
        0,
        Math.round(Number(item.base_cost_snapshot) || 0),
      ),
      allowance_cost: Math.max(0, Math.round(Number(item.allowance_cost) || 0)),
      note: item.note ?? '',
      sort_order: item.sort_order ?? 100,
    });
  }

  if (payloadsToInsert.length === 0) {
    return {
      copiedCount: 0,
      copiedRoomsCount: insertedOverrides.length,
      skippedCount: sourceAssignments.length,
      sourceTotalCount: sourceAssignments.length,
      targetSchedule,
      insertedAssignments: [],
      insertedOverrides,
    };
  }

  const { data: insertedData, error: insertErr } = await supabase
    .from('roster_assignments')
    .insert(payloadsToInsert)
    .select('*');

  if (insertErr) {
    throw new Error(
      insertErr.message || 'Không thể sao chép phân công từ hôm qua.',
    );
  }

  const insertedAssignments = ((insertedData ?? []) as RosterAssignment[]).map(
    (a) => ({
      ...a,
      daily_override_id: a.daily_override_id ?? null,
      base_cost_snapshot: Number(a.base_cost_snapshot ?? 0),
      allowance_cost: Number(a.allowance_cost ?? 0),
      total_cost: Number(
        a.total_cost ??
          Number(a.base_cost_snapshot ?? 0) + Number(a.allowance_cost ?? 0),
      ),
    }),
  );

  return {
    copiedCount: insertedAssignments.length,
    copiedRoomsCount: insertedOverrides.length,
    skippedCount: sourceAssignments.length - insertedAssignments.length,
    sourceTotalCount: sourceAssignments.length,
    targetSchedule,
    insertedAssignments,
    insertedOverrides,
  };
}
