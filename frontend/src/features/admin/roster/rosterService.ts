export async function renameCampaignPosition(
  scheduleId: string,
  oldName: string,
  newName: string,
  currentPositionList: string[],
): Promise<RosterSchedule> {
  const trimmedOld = oldName.trim();
  const trimmedNew = newName.trim();
  if (!trimmedNew) {
    throw new Error('Tên vị trí không được để trống.');
  }

  const nextPositions = Array.from(
    new Set(
      currentPositionList.map((p) => (p.trim() === trimmedOld ? trimmedNew : p.trim())).filter(Boolean),
    ),
  );

  const [{ data, error }, { error: assignErr }] = await Promise.all([
    supabase
      .from('roster_schedules')
      .update({
        position_list: nextPositions,
        updated_at: new Date().toISOString(),
      })
      .eq('id', scheduleId)
      .select('*')
      .single(),
    supabase
      .from('roster_assignments')
      .update({ position_label: trimmedNew })
      .eq('schedule_id', scheduleId)
      .eq('position_label', trimmedOld),
  ]);

  if (error) {
    throw new Error(error.message || 'Không thể đổi tên vị trí đoàn khám.');
  }
  if (assignErr) {
    throw new Error(assignErr.message || 'Không thể cập nhật vị trí cho nhân sự đã gán.');
  }

  return normalizeRosterSchedule(data as RosterSchedule);
}

export async function removeCampaignPositionAndAssignments(
  scheduleId: string,
  positionName: string,
  currentPositionList: string[],
): Promise<RosterSchedule> {
  const trimmed = positionName.trim();
  const nextPositions = currentPositionList
    .map((p) => p.trim())
    .filter((p) => p && p !== trimmed);

  const { error: delErr } = await supabase
    .from('roster_assignments')
    .delete()
    .eq('schedule_id', scheduleId)
    .eq('position_label', trimmed);

  if (delErr) {
    throw new Error(delErr.message || 'Không thể xóa nhân sự thuộc vị trí này.');
  }

  return updateCampaignPositionList(scheduleId, nextPositions);
}

